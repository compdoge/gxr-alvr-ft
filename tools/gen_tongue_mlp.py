#!/usr/bin/env python3
"""Generate headset/gxr_tongue_mlp.h from the tongue research artifacts.

Embeds:
  * the exact 11->5 tongue mapper MLP (11-128-128-64-5, sigmoid) from
    results/tongue-map.json -> used to compute the 5 XR DOFs (the DOF regressor
    the calibration was fit against),
  * per-param linear readouts (ROLL / FLAT / SQUISH / TWIST) from
    results/tongue-calib/extra_axes.json.

Readout contract (matches the calibration):
    score = intercept + dot(x, axis) + dot([OUT,LEFT,RIGHT,UP,DOWN], dof_coef)

Usage:
    python tools/gen_tongue_mlp.py \
        --map   <results/tongue-map.json> \
        --calib <results/tongue-calib/extra_axes.json> \
        --out   headset/gxr_tongue_mlp.h
"""
import argparse
import json

POSES = {"roll": "ROLL"}


def cfmt(v):
    return ("%.9g" % float(v)) + "f"


def arr(name, dims, data):
    # data is a flat list in row-major order; dims is a list of ints
    total = 1
    for d in dims:
        total *= d
    assert len(data) == total, (name, len(data), total)
    dstr = "".join("[%d]" % d for d in dims)
    out = ["static const float %s%s = {" % (name, dstr)]
    if len(dims) == 2:
        rows, cols = dims
        for r in range(rows):
            row = data[r * cols:(r + 1) * cols]
            out.append("    { " + ", ".join(cfmt(x) for x in row) + " },")
    else:
        per = 12
        for i in range(0, total, per):
            out.append("    " + ", ".join(cfmt(x) for x in data[i:i + per]) + ",")
    out.append("};")
    return "\n".join(out)


def flat2(v):
    return [x for row in v for x in row]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--map", required=True)
    ap.add_argument("--calib", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    m = json.load(open(args.map, encoding="utf-8"))
    mp = m["mapper"]
    order = [s.upper().replace("TONGUE_", "") for s in mp["output_order"]]
    if order != ["OUT", "LEFT", "RIGHT", "UP", "DOWN"]:
        raise SystemExit("unexpected mapper output_order: %r (expected OUT,LEFT,RIGHT,UP,DOWN)" % (mp["output_order"],))

    cal = json.load(open(args.calib, encoding="utf-8"))["poses"]

    L = ["/* AUTO-GENERATED by tools/gen_tongue_mlp.py - do not edit by hand.",
         " * Source: results/tongue-map.json + results/tongue-calib/extra_axes.json */",
         "#ifndef GXR_TONGUE_MLP_H",
         "#define GXR_TONGUE_MLP_H",
         "",
         "#define TONGUE_IN 11",
         "#define TONGUE_H1 128",
         "#define TONGUE_H2 128",
         "#define TONGUE_H3 64",
         "#define TONGUE_DOF 5",
         ""]
    L.append(arr("TONGUE_W1", [128, 11], flat2(mp["W1"])))
    L.append(arr("TONGUE_B1", [128], mp["b1"]))
    L.append(arr("TONGUE_W2", [128, 128], flat2(mp["W2"])))
    L.append(arr("TONGUE_B2", [128], mp["b2"]))
    L.append(arr("TONGUE_W3", [64, 128], flat2(mp["W3"])))
    L.append(arr("TONGUE_B3", [64], mp["b3"]))
    L.append(arr("TONGUE_W4", [5, 64], flat2(mp["W4"])))
    L.append(arr("TONGUE_B4", [5], mp["b4"]))
    L.append("")

    for key, pose in POSES.items():
        p = cal[pose]
        up = key.upper()
        L.append(arr("TR_%s_AXIS" % up, [11], p["axis"]))
        L.append(arr("TR_%s_DOF" % up, [5], p["dof_coef"]))
        L.append("static const float TR_%s_INT = %s;" % (up, cfmt(p["intercept"])))
        L.append("")

    L.append("#endif /* GXR_TONGUE_MLP_H */")
    open(args.out, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print("wrote", args.out)


if __name__ == "__main__":
    main()
